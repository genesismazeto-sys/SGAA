"""PostgreSQL-readiness Unit 5-A: real PostgreSQL integration gate.

Runs only when ``SGAA_PG_TEST_URL`` supplies administrative access to a local
PostgreSQL server (PG 15+); otherwise the whole module skips.  The lane NEVER
provisions into, resets or drops schemas of the database named in that URL:
for every test it creates uniquely named ``sgaa_u5a_test_*`` databases, records
them in a session-owned registry, and drops only those during teardown.  If the
configured role cannot CREATE DATABASE the module skips clearly.  Every test
then works inside its own throwaway schema of a fixture-owned database -- the
explicit CLI lane provisions a fixture-owned empty database.

The gate proves, on a real server:

1. provisioning DDL completes;
2. a second provision is a safe no-op when the schema matches;
3. partial/incompatible schemas fail closed without destructive repair;
4. every required table exists;
5. identity is ``GENERATED BY DEFAULT`` (explicit IDs accepted) and generated
   identity works, including advancing the sequence after explicit loading;
6. all material and the composite foreign key compile and enforce;
7. the partial unique predicates enforce;
8. JSON text checks are PG15-compatible and refuse malformed input as
   constraint violations;
9. the timestamp helper/default is exact text UTC at second resolution;
10. all eleven triggers compile and enforce positive and negative cases;
11. ``validate_pg_schema`` passes a valid schema and is read-only;
12. material schema mutations are detected by the validator;
13. psycopg diagnostics carry the explicit expected constraint names.
"""
