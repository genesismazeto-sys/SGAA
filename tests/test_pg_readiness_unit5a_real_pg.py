def test_timestamp_helper_is_utc_text_seconds_and_lexically_ordered(provisioned_schema):
    connection, schema = provisioned_schema
    with connection.cursor() as cursor:
        cursor.execute("SET TIME ZONE 'America/Sao_Paulo'")
        cursor.execute("SELECT sgaa_utcnow_text()")
        value = cursor.fetchone()[0]
        assert re.fullmatch(r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}", value)
        parsed = datetime.strptime(value, "%Y-%m-%d %H:%M:%S").replace(
            tzinfo=timezone.utc
        )
        assert abs(
            (parsed - datetime.now(timezone.utc)).total_seconds()
        ) < 120
        cursor.execute(
            "INSERT INTO atividade_base(nome_conceito) VALUES('Default stamp') "
            "RETURNING created_at"
        )
        default_value = cursor.fetchone()[0]
        assert re.fullmatch(r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}", default_value)
        first = value
        cursor.execute("SELECT pg_sleep(1.1)")
        cursor.execute("SELECT sgaa_utcnow_text()")
        second = cursor.fetchone()[0]
        assert first < second
        delta = datetime.strptime(second, "%Y-%m-%d %H:%M:%S") - datetime.strptime(
            first, "%Y-%m-%d %H:%M:%S"
        )
        assert delta >= timedelta(seconds=1)
    connection.commit()


