def test_foreign_keys_and_composite_fk_compile_and_enforce(provisioned_schema):
    connection, schema = provisioned_schema
    with connection.cursor() as cursor:
        course, matrix, turma = _seed_course_matrix_turma(cursor)
        base_one, version_one = _seed_base_version(cursor, conceito="Base U5A 1")
        base_two, version_two = _seed_base_version(cursor, conceito="Base U5A 2")
        base_three, version_three = _seed_base_version(cursor, conceito="Base U5A 3")
        cursor.execute(
            "INSERT INTO matriz_atividade_versao_item(matriz_id,atividade_base_id,"
            "atividade_versao_id) VALUES(%s,%s,%s)",
            (matrix, base_one, version_one),
        )
    # (version_two, base_three) satisfies both (matriz, base) / (matriz, versao)
    # uniqueness but not the composite FK to atividade_versao(id, atividade_base_id).
    _assert_constraint_violation(
        connection,
        "INSERT INTO matriz_atividade_versao_item(matriz_id,atividade_base_id,"
        "atividade_versao_id) VALUES(%s,%s,%s)",
        (matrix, base_three, version_two),
        psycopg.errors.ForeignKeyViolation,
        "fk_matriz_atividade_versao_item_versao_base",
    )
    _assert_constraint_violation(
        connection,
        "DELETE FROM matrizes_atividades WHERE id=%s",
        (matrix,),
        (psycopg.errors.ForeignKeyViolation, psycopg.errors.RestrictViolation),
        "fk_turmas_matriz_id",
    )
    connection.rollback()


