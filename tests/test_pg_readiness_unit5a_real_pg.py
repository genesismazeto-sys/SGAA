def _probe_sqlstate(connection, sql, params=None, *, savepoint="u5a_probe"):
    """Execute a statement expected to fail without discarding prior setup."""
    connection.execute(f"SAVEPOINT {savepoint}")
    try:
        with connection.cursor() as cursor:
            cursor.execute(sql, params)
    except Exception as exc:
        connection.execute(f"ROLLBACK TO SAVEPOINT {savepoint}")
        connection.execute(f"RELEASE SAVEPOINT {savepoint}")
        return exc
    connection.execute(f"RELEASE SAVEPOINT {savepoint}")
    raise AssertionError(f"statement unexpectedly succeeded: {sql}")


def _assert_refused(connection, table, sql, params=None):
    pg = _pg()
    before = _count(connection, table)
    error = _probe_sqlstate(connection, sql, params)
    assert getattr(error, "sqlstate", None) == pg.PG_BUSINESS_RULE_SQLSTATE, (
        f"expected {pg.PG_BUSINESS_RULE_SQLSTATE}, got {error!r}"
    )
    assert _count(connection, table) == before
    return error


def _assert_constraint_violation(
    connection, sql, params, error_type, constraint_name
):
    error = _probe_sqlstate(connection, sql, params)
    assert isinstance(error, error_type), error
    assert error.diag.constraint_name == constraint_name, error.diag.constraint_name
    return error


