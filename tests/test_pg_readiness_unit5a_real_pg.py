def test_identity_is_by_default_and_sequence_can_advance(provisioned_schema):
    connection, schema = provisioned_schema
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT a.attidentity FROM pg_catalog.pg_attribute a "
            "JOIN pg_catalog.pg_class c ON c.oid=a.attrelid "
            "JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname=current_schema() AND c.relname='usuarios' "
            "AND a.attname='id'"
        )
        assert cursor.fetchone()[0] == "d"
        cursor.execute(
            "INSERT INTO usuarios(id,nome,email,senha,tipo) "
            "VALUES(9000,'Explicit','explicit@u5a.test','hash','admin')"
        )
        cursor.execute(
            "INSERT INTO usuarios(nome,email,senha,tipo) "
            "VALUES('Generated','generated@u5a.test','hash','admin') RETURNING id"
        )
        generated = cursor.fetchone()[0]
        assert generated != 9000
        cursor.execute("SELECT pg_get_serial_sequence('usuarios','id')")
        sequence = cursor.fetchone()[0]
        assert sequence
        cursor.execute(f"SELECT setval('{sequence}', (SELECT MAX(id) FROM usuarios))")
        cursor.execute(
            "INSERT INTO usuarios(nome,email,senha,tipo) "
            "VALUES('After','after@u5a.test','hash','admin') RETURNING id"
        )
        assert cursor.fetchone()[0] == 9001
    connection.commit()


