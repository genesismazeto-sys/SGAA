_NOW = f"{PG_UTC_NOW_FUNCTION}()"


def _col(name, type_, not_null=False, default=None, identity=None):
    return {
        "name": name,
        "type": type_,
        "not_null": bool(not_null),
        "default": default,
        "identity": identity,
    }


def _text(name, not_null=False, default=None):
    return _col(name, "text", not_null=not_null, default=default)


def _integer(name, not_null=False, default=None):
    return _col(name, "integer", not_null=not_null, default=default)


def _real(name, not_null=False, default=None):
    return _col(name, "double precision", not_null=not_null, default=default)


def _bytea(name, not_null=False, default=None):
    return _col(name, "bytea", not_null=not_null, default=default)


def _identity(name):
    return _col(name, "integer", not_null=True, identity="BY DEFAULT")


def _pk(table, *columns):
    return {"name": f"{table}_pkey", "columns": list(columns)}


def _uq(table, *columns, name=None):
    return {"name": name or f"uq_{table}_{'_'.join(columns)}", "columns": list(columns)}


def _ck(table, rule, expression, name=None):
    return {"name": name or f"ck_{table}_{rule}", "expression": expression}


def _fk(
    table,
    columns,
    references_table,
    references_columns,
    *,
    on_delete="NO ACTION",
    on_update="NO ACTION",
    name=None,
):
    return {
        "name": name or f"fk_{table}_{'_'.join(columns)}",
        "columns": list(columns),
        "references_table": references_table,
        "references_columns": list(references_columns),
        "on_delete": on_delete,
        "on_update": on_update,
    }


def _spec(columns, primary_key, uniques=(), checks=(), foreign_keys=()):
    return {
        "columns": list(columns),
        "primary_key": primary_key,
        "uniques": list(uniques),
        "checks": list(checks),
        "foreign_keys": list(foreign_keys),
    }


def _index(name, table, columns, *, unique=False, predicate=None, descending=None):
    columns = list(columns)
    return {
        "name": name,
        "table": table,
        "unique": bool(unique),
        "columns": columns,
        "descending": list(descending) if descending is not None else [False] * len(columns),
        "predicate": predicate,
    }


def _trigger(name, table, events, function, *, columns=None):
    return {
        "name": name,
        "table": table,
        "timing": "BEFORE",
        "events": list(events),
        "columns": list(columns) if columns else None,
        "function": function,
    }


def _image_spec(table, owner_column, owner_table, mime_types, max_bytes, max_edge):
    """One v13 image side table; the same constraints as ``app.prod1_images_ddl``."""
    mime_list = ",".join(f"'{mime}'" for mime in mime_types)
    return _spec(
        [
            _integer(owner_column, not_null=True),
            _text("mime_type", not_null=True),
            _integer("size_bytes", not_null=True),
            _text("sha256", not_null=True),
            _integer("width", not_null=True),
            _integer("height", not_null=True),
            _bytea("conteudo", not_null=True),
            _text("atualizado_em", not_null=True, default=_NOW),
        ],
        _pk(table, owner_column),
        checks=[
            _ck(table, "mime_type", f"mime_type IN ({mime_list})"),
            _ck(table, "size_bytes", f"size_bytes > 0 AND size_bytes <= {max_bytes}"),
            _ck(table, "sha256", "sha256 ~ '^[0-9a-f]{64}$'"),
            _ck(table, "width", f"width > 0 AND width <= {max_edge}"),
            _ck(table, "height", f"height > 0 AND height <= {max_edge}"),
            _ck(table, "conteudo", "octet_length(conteudo) = size_bytes"),
        ],
        foreign_keys=[
            _fk(
                table,
                [owner_column],
                owner_table,
                ["id"],
                on_delete="CASCADE",
                on_update="CASCADE",
            ),
        ],
    )


def _in_list(values):
    return ",".join(f"'{value}'" for value in values)


def _ts_check(column):
    """Exact canonical ``YYYY-MM-DD HH:MM:SS`` text that is also a real date-time.

    The time part is bounded lexically (hour 00-23, minute / second 00-59):
    PostgreSQL's timestamp input otherwise accepts and silently normalizes
    second 60 and hour 24, which the SQLite ``_ts`` refuses.  The helper still
    validates the calendar date (and refuses year 0000).
    """
    return (
        f"{column} ~ '^[0-9]{{4}}-[0-9]{{2}}-[0-9]{{2}} ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$' "
        f"AND {PG_DATETIME_VALID_FUNCTION}({column})"
    )


def _opt_ts_check(column):
    return f"{column} IS NULL OR ({_ts_check(column)})"


def _code_check(column):
    return f"{column} IS NULL OR {column} ~ '^[A-Z0-9_]{{1,{ERROR_CODE_MAX_LENGTH}}}$'"


def _bucket_check(column):
    return f"{column} ~ '^[a-z0-9._-]{{1,{STORAGE_BUCKET_MAX_LENGTH}}}$'"


def _key_check(column):
    # PostgreSQL AREs cap a {m,n} bound at 255: lengths go to char_length().
    return (
        f"{column} ~ '^[A-Za-z0-9_.-][A-Za-z0-9/_.-]*$' "
        f"AND char_length({column}) <= {STORAGE_KEY_MAX_LENGTH} "
        f"AND position('..' in {column}) = 0"
    )


def _account_key_check(column):
    """Logical provider-account key: NULL or SHA-256 lowercase hex (no FK, by design)."""
    return f"{column} IS NULL OR {column} ~ '^[0-9a-f]{{64}}$'"


