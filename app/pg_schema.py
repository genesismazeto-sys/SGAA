def _fetch(connection, sql):
    cursor = connection.execute(sql)
    return [tuple(row) for row in cursor.fetchall()]


def _require_server_encoding(connection):
    """Fail fast unless the server encoding is UTF8.

    ``sgaa_human_text_key`` relies on ``normalize()`` and on Unicode escapes,
    both of which require a UTF8 server; nothing else in the contract is
    meaningful without it.
    """
    rows = _fetch(connection, "SELECT current_setting('server_encoding')")
    encoding = str(rows[0][0]) if rows else None
    if encoding != PG_REQUIRED_SERVER_ENCODING:
        raise PostgresSchemaError(
            f"PostgreSQL server_encoding must be {PG_REQUIRED_SERVER_ENCODING!r}, "
            f"found {encoding!r}"
        )


def _current_schema(connection):
    rows = _fetch(connection, "SELECT current_schema()")
    schema = rows[0][0]
    if not schema:
        raise PostgresSchemaError(
            "no current schema is selected; PostgreSQL provisioning needs a schema"
        )
    return str(schema)


def _schema_relation_names(connection):
    return {
        str(row[0])
        for row in _fetch(
            connection,
            "SELECT c.relname FROM pg_catalog.pg_class c "
            "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = current_schema() "
            "AND c.relkind IN ('r','p','v','m','i','S')",
        )
    }


def _schema_function_names(connection):
    return {
        str(row[0])
        for row in _fetch(
            connection,
            "SELECT p.proname FROM pg_catalog.pg_proc p "
            "JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace "
            "WHERE n.nspname = current_schema()",
        )
    }


def require_pg_tables(connection, *names):
    """Read-only assertion that the given application tables exist."""
    present = {
        str(row[0])
        for row in _fetch(
            connection,
            "SELECT c.relname FROM pg_catalog.pg_class c "
            "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = current_schema() AND c.relkind IN ('r','p')",
        )
    }
    missing = sorted(set(names) - present)
    if missing:
        raise PostgresSchemaError(
            f"PostgreSQL prod-1 schema objects missing: {missing!r}"
        )


