def _normalize_fragment(value):
    text = re.sub(r"::(?:text|character varying|bpchar)", "", str(value or ""))
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _normalize_predicate(value):
    text = _normalize_fragment(value).lower()
    while text.startswith("(") and text.endswith(")"):
        text = text[1:-1]
    return re.sub(r"[\s()]", "", text)


def _normalize_default(value):
    return _normalize_fragment(value)


_FK_ACTION_CODES = {
    "a": "NO ACTION",
    "r": "RESTRICT",
    "c": "CASCADE",
    "n": "SET NULL",
    "d": "SET DEFAULT",
}


def _catalog_columns(connection):
    rows = _fetch(
        connection,
        "SELECT c.relname, a.attname, "
        "pg_catalog.format_type(a.atttypid, a.atttypmod), "
        "a.attnotnull, pg_catalog.pg_get_expr(d.adbin, d.adrelid), a.attidentity "
        "FROM pg_catalog.pg_attribute a "
        "JOIN pg_catalog.pg_class c ON c.oid = a.attrelid "
        "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
        "LEFT JOIN pg_catalog.pg_attrdef d "
        "  ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
        "WHERE n.nspname = current_schema() AND c.relkind IN ('r','p') "
        "AND a.attnum > 0 AND NOT a.attisdropped "
        "ORDER BY c.relname, a.attnum",
    )
    columns = {}
    for table, name, type_, not_null, default, identity in rows:
        columns.setdefault(str(table), []).append(
            {
                "name": str(name),
                "type": str(type_),
                "not_null": bool(not_null),
                "default": None if default is None else str(default),
                "identity": str(identity or ""),
            }
        )
    return columns


def _attribute_names(connection):
    return {
        (int(relid), int(attnum)): str(name)
        for relid, attnum, name in _fetch(
            connection,
            "SELECT a.attrelid, a.attnum, a.attname "
            "FROM pg_catalog.pg_attribute a WHERE a.attnum > 0",
        )
    }


def _relation_names_by_oid(connection):
    return {
        int(oid): str(name)
        for oid, name in _fetch(
            connection,
            "SELECT c.oid, c.relname FROM pg_catalog.pg_class c",
        )
    }


def _catalog_constraints(connection):
    attributes = _attribute_names(connection)
    relations = _relation_names_by_oid(connection)
    rows = _fetch(
        connection,
        "SELECT con.conrelid, c.relname, con.conname, con.contype, "
        "con.confdeltype, con.confupdtype, con.conkey, con.confkey, "
        "con.confrelid, pg_catalog.pg_get_constraintdef(con.oid, true) "
        "FROM pg_catalog.pg_constraint con "
        "JOIN pg_catalog.pg_class c ON c.oid = con.conrelid "
        "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = current_schema() AND con.contype IN ('p','u','c','f')",
    )
    constraints = []
    for (
        relid,
        table,
        name,
        contype,
        delete_code,
        update_code,
        conkey,
        confkey,
        confrelid,
        definition,
    ) in rows:
        entry = {
            "table": str(table),
            "name": str(name),
            "contype": str(contype),
            "definition": str(definition),
        }
        if conkey is not None:
            entry["columns"] = [
                attributes[(int(relid), int(attnum))] for attnum in conkey
            ]
        if confrelid:
            entry["references_table"] = relations.get(int(confrelid))
            entry["references_columns"] = [
                attributes[(int(confrelid), int(attnum))]
                for attnum in (confkey or [])
            ]
            entry["on_delete"] = _FK_ACTION_CODES.get(
                str(delete_code), str(delete_code)
            )
            entry["on_update"] = _FK_ACTION_CODES.get(
                str(update_code), str(update_code)
            )
        constraints.append(entry)
    return constraints


def _catalog_indexes(connection):
    rows = _fetch(
        connection,
        "SELECT ic.relname, t.relname, i.indisunique, i.indisprimary, "
        "pg_catalog.pg_get_expr(i.indpred, i.indrelid), a.attname, "
        "k.options, k.ordinality "
        "FROM pg_catalog.pg_index i "
        "JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid "
        "JOIN pg_catalog.pg_class t ON t.oid = i.indrelid "
        "JOIN pg_catalog.pg_namespace n ON n.oid = t.relnamespace "
        "JOIN LATERAL unnest(i.indkey, i.indoption) WITH ORDINALITY "
        "  AS k(attnum, options, ordinality) ON true "
        "LEFT JOIN pg_catalog.pg_attribute a "
        "  ON a.attrelid = i.indrelid AND a.attnum = k.attnum "
        "WHERE n.nspname = current_schema() "
        "ORDER BY ic.relname, k.ordinality",
    )
    indexes = {}
    for name, table, unique, primary, predicate, column, options, _ in rows:
        entry = indexes.setdefault(
            str(name),
            {
                "table": str(table),
                "unique": bool(unique),
                "primary": bool(primary),
                "predicate": None if predicate is None else str(predicate),
                "columns": [],
                "descending": [],
            },
        )
        entry["columns"].append(None if column is None else str(column))
        entry["descending"].append(bool(int(options) & 1))
    return indexes


def _catalog_triggers(connection):
    rows = _fetch(
        connection,
        "SELECT t.tgname, c.relname, p.proname, "
        "pg_catalog.pg_get_triggerdef(t.oid, true) "
        "FROM pg_catalog.pg_trigger t "
        "JOIN pg_catalog.pg_class c ON c.oid = t.tgrelid "
        "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
        "JOIN pg_catalog.pg_proc p ON p.oid = t.tgfoid "
        "WHERE n.nspname = current_schema() AND NOT t.tgisinternal",
    )
    return {
        str(name): {
            "table": str(table),
            "function": str(function),
            "definition": str(definition),
        }
        for name, table, function, definition in rows
    }


def _normalized_trigger_definition(definition, schema):
    text = str(definition).lower()
    text = re.sub(rf'"?{re.escape(schema.lower())}"?\s*\.', "", text)
    text = text.replace('"', "")
    return re.sub(r"\s+", " ", text).strip()


def validate_pg_schema(connection):
    """Read-only validation of the material PostgreSQL prod-1/v14 contract.

    Returns a summary dict.  Raises :class:`PostgresSchemaError` on the first
    material divergence (missing/extra table, column, constraint, index,
    trigger, wrong FK action, wrong identity or wrong ``pg_schema_meta``
    epoch/version/digest).  Executes SELECT statements only.  The UTF8
    server-encoding precondition is checked first.
    """
    _require_server_encoding(connection)
    schema = _current_schema(connection)
    actual_tables = {
        str(row[0])
        for row in _fetch(
            connection,
            "SELECT c.relname FROM pg_catalog.pg_class c "
            "JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = current_schema() AND c.relkind IN ('r','p')",
        )
    }
    expected_tables = set(PG_SCHEMA_TABLES)
    missing = sorted(expected_tables - actual_tables)
    unexpected = sorted(actual_tables - expected_tables)
    if missing or unexpected:
        raise PostgresSchemaError(
            "PostgreSQL table census mismatch: "
            f"missing={missing!r} unexpected={unexpected!r}"
        )

    columns = _catalog_columns(connection)
    for table in PG_SCHEMA_TABLES:
        actual = columns.get(table, [])
        expected = PG_TABLE_SPECS[table]["columns"]
        if [column["name"] for column in actual] != [
            column["name"] for column in expected
        ]:
            raise PostgresSchemaError(
                f"PostgreSQL column census mismatch for {table}: "
                f"{[column['name'] for column in actual]!r}"
            )
        for actual_column, expected_column in zip(actual, expected):
            label = f"{table}.{expected_column['name']}"
            if actual_column["type"] != expected_column["type"]:
                raise PostgresSchemaError(
                    f"PostgreSQL type mismatch for {label}: "
                    f"{actual_column['type']!r} != {expected_column['type']!r}"
                )
            if actual_column["not_null"] != bool(expected_column["not_null"]):
                raise PostgresSchemaError(f"PostgreSQL nullability mismatch for {label}")
            if expected_column["identity"]:
                if actual_column["identity"] != "d":
                    raise PostgresSchemaError(
                        f"PostgreSQL identity for {label} must be BY DEFAULT"
                    )
            elif actual_column["identity"]:
                raise PostgresSchemaError(f"unexpected identity on {label}")
            expected_default = expected_column["default"]
            if expected_default is not None and not expected_column["identity"]:
                if _normalize_default(actual_column["default"]) != _normalize_default(
                    expected_default
                ):
                    raise PostgresSchemaError(
                        f"PostgreSQL default mismatch for {label}: "
                        f"{actual_column['default']!r} != {expected_default!r}"
                    )

    constraints = _catalog_constraints(connection)
    actual_by_kind = {"p": {}, "u": {}, "c": {}, "f": {}}
    for entry in constraints:
        key = (entry["table"], entry["name"])
        actual_by_kind[entry["contype"]][key] = entry
    for table in PG_SCHEMA_TABLES:
        spec = PG_TABLE_SPECS[table]
        primary_key = spec["primary_key"]
        if (table, primary_key["name"]) not in actual_by_kind["p"]:
            raise PostgresSchemaError(
                f"missing primary key {primary_key['name']}"
            )
        pk_columns = actual_by_kind["p"][(table, primary_key["name"])]["columns"]
        if pk_columns != list(primary_key["columns"]):
            raise PostgresSchemaError(
                f"primary key columns mismatch for {primary_key['name']}: "
                f"{pk_columns!r}"
            )
        for unique in spec["uniques"]:
            entry = actual_by_kind["u"].get((table, unique["name"]))
            if entry is None:
                raise PostgresSchemaError(f"missing unique constraint {unique['name']}")
            if entry["columns"] != list(unique["columns"]):
                raise PostgresSchemaError(
                    f"unique constraint columns mismatch for {unique['name']}: "
                    f"{entry['columns']!r}"
                )
        for check in spec["checks"]:
            entry = actual_by_kind["c"].get((table, check["name"]))
            if entry is None:
                raise PostgresSchemaError(f"missing check constraint {check['name']}")
            for helper in (
                PG_JSON_VALID_FUNCTION,
                PG_JSON_OBJECT_FUNCTION,
            ):
                if helper in check["expression"] and helper not in entry["definition"]:
                    raise PostgresSchemaError(
                        f"check constraint {check['name']} lost its {helper} check"
                    )
        for foreign_key in spec["foreign_keys"]:
            entry = actual_by_kind["f"].get((table, foreign_key["name"]))
            if entry is None:
                raise PostgresSchemaError(
                    f"missing foreign key {foreign_key['name']}"
                )
            if entry["columns"] != list(foreign_key["columns"]):
                raise PostgresSchemaError(
                    f"foreign key columns mismatch for {foreign_key['name']}"
                )
            if entry.get("references_table") != foreign_key["references_table"]:
                raise PostgresSchemaError(
                    f"foreign key target mismatch for {foreign_key['name']}"
                )
            if entry.get("references_columns") != list(
                foreign_key["references_columns"]
            ):
                raise PostgresSchemaError(
                    f"foreign key referenced columns mismatch for "
                    f"{foreign_key['name']}"
                )
            if entry.get("on_delete") != foreign_key["on_delete"]:
                raise PostgresSchemaError(
                    f"foreign key ON DELETE mismatch for {foreign_key['name']}: "
                    f"{entry.get('on_delete')!r}"
                )
            if entry.get("on_update") != foreign_key["on_update"]:
                raise PostgresSchemaError(
                    f"foreign key ON UPDATE mismatch for {foreign_key['name']}: "
                    f"{entry.get('on_update')!r}"
                )
    expected_constraints = {
        (table, spec["primary_key"]["name"])
        for table, spec in PG_TABLE_SPECS.items()
    }
    expected_constraints |= {
        (table, unique["name"])
        for table, spec in PG_TABLE_SPECS.items()
        for unique in spec["uniques"]
    }
    expected_constraints |= {
        (table, check["name"])
        for table, spec in PG_TABLE_SPECS.items()
        for check in spec["checks"]
    }
    expected_constraints |= {
        (table, foreign_key["name"])
        for table, spec in PG_TABLE_SPECS.items()
        for foreign_key in spec["foreign_keys"]
    }
    actual_constraints = {
        (entry["table"], entry["name"])
        for entries in actual_by_kind.values()
        for entry in entries.values()
    }
    extra = sorted(actual_constraints - expected_constraints)
    missing_constraints = sorted(expected_constraints - actual_constraints)
    if extra or missing_constraints:
        raise PostgresSchemaError(
            "PostgreSQL constraint census mismatch: "
            f"missing={missing_constraints!r} unexpected={extra!r}"
        )

    indexes = _catalog_indexes(connection)
    constraint_index_names = {
        name for _, name in expected_constraints if name.endswith(("_pkey",))
    } | {
        unique["name"]
        for spec in PG_TABLE_SPECS.values()
        for unique in spec["uniques"]
    }
    for name, expected in PG_EXPLICIT_INDEXES.items():
        actual = indexes.get(name)
        if actual is None:
            raise PostgresSchemaError(f"missing index {name}")
        if actual["table"] != expected["table"]:
            raise PostgresSchemaError(f"index table mismatch for {name}")
        if actual["unique"] != expected["unique"]:
            raise PostgresSchemaError(f"index uniqueness mismatch for {name}")
        if actual["columns"] != list(expected["columns"]):
            raise PostgresSchemaError(
                f"index columns mismatch for {name}: {actual['columns']!r}"
            )
        if actual["descending"] != list(expected["descending"]):
            raise PostgresSchemaError(f"index order mismatch for {name}")
        actual_predicate = (
            None
            if actual["predicate"] is None
            else _normalize_predicate(actual["predicate"])
        )
        expected_predicate = (
            None
            if expected["predicate"] is None
            else _normalize_predicate(expected["predicate"])
        )
        if actual_predicate != expected_predicate:
            raise PostgresSchemaError(
                f"index predicate mismatch for {name}: "
                f"{actual['predicate']!r} != {expected['predicate']!r}"
            )
    unexpected_indexes = sorted(
        name
        for name in indexes
        if name not in PG_EXPLICIT_INDEXES and name not in constraint_index_names
    )
    if unexpected_indexes:
        raise PostgresSchemaError(
            f"unexpected PostgreSQL indexes: {unexpected_indexes!r}"
        )

    triggers = _catalog_triggers(connection)
    expected_trigger_names = {trigger["name"] for trigger in PG_TRIGGERS}
    if set(triggers) != expected_trigger_names:
        raise PostgresSchemaError(
            "PostgreSQL trigger census mismatch: "
            f"missing={sorted(expected_trigger_names - set(triggers))!r} "
            f"unexpected={sorted(set(triggers) - expected_trigger_names)!r}"
        )
    for trigger in PG_TRIGGERS:
        actual = triggers[trigger["name"]]
        if actual["table"] != trigger["table"]:
            raise PostgresSchemaError(
                f"trigger table mismatch for {trigger['name']}"
            )
        if actual["function"] != trigger["function"]:
            raise PostgresSchemaError(
                f"trigger function mismatch for {trigger['name']}"
            )
        definition = _normalized_trigger_definition(actual["definition"], schema)
        event = trigger["events"][0].lower()
        if trigger["columns"]:
            event += " of " + ", ".join(trigger["columns"])
        expected_fragment = (
            f"create trigger {trigger['name']} before {event} on "
            f"{trigger['table']} for each row execute function "
            f"{trigger['function']}()"
        )
        if expected_fragment not in definition:
            raise PostgresSchemaError(
                f"trigger definition mismatch for {trigger['name']}: "
                f"{actual['definition']!r}"
            )

    functions = _schema_function_names(connection)
    required_functions = set(PG_HELPERS) | {
        trigger["function"] for trigger in PG_TRIGGERS
    }
    missing_functions = sorted(required_functions - functions)
    if missing_functions:
        raise PostgresSchemaError(
            f"missing PostgreSQL functions: {missing_functions!r}"
        )

    meta_rows = _fetch(
        connection,
        "SELECT id, schema_epoch, schema_version, contract_sha256, applied_at "
        f"FROM {PG_SCHEMA_META_TABLE} ORDER BY id",
    )
    if len(meta_rows) != 1:
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE} must hold exactly one row, found {len(meta_rows)}"
        )
    meta_id, epoch, version, digest, applied_at = meta_rows[0]
    if int(meta_id) != PG_SCHEMA_META_ID:
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE}.id must be {PG_SCHEMA_META_ID}"
        )
    if str(epoch) != PG_SCHEMA_EPOCH:
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE}.schema_epoch mismatch: {epoch!r}"
        )
    if int(version) != PG_SCHEMA_VERSION:
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE}.schema_version mismatch: {version!r}"
        )
    if str(digest) != PG_CONTRACT_SHA256:
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE}.contract_sha256 does not match the "
            "application-owned contract digest"
        )
    if not re.fullmatch(
        r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}", str(applied_at or "")
    ):
        raise PostgresSchemaError(
            f"{PG_SCHEMA_META_TABLE}.applied_at is not UTC text seconds"
        )

    return {
        "schema_epoch": PG_SCHEMA_EPOCH,
        "schema_version": PG_SCHEMA_VERSION,
        "contract_sha256": PG_CONTRACT_SHA256,
        "table_count": len(actual_tables),
        "constraint_count": len(actual_constraints),
        "index_count": len(indexes),
        "trigger_count": len(triggers),
    }


