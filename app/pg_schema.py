_IDENTIFIER_RE = re.compile(r"^[a-z_][a-z0-9_]*$")


def _assert_identifier(name):
    if len(name) > 63 or not _IDENTIFIER_RE.match(name):
        raise PostgresSchemaError(
            f"invalid PostgreSQL object name in contract: {name!r}"
        )
    return name


def _column_ddl(column):
    name = _assert_identifier(column["name"])
    if column["identity"]:
        return f"{name} integer GENERATED BY DEFAULT AS IDENTITY"
    fragments = [name, column["type"]]
    if column["not_null"]:
        fragments.append("NOT NULL")
    if column["default"] is not None:
        fragments.append(f"DEFAULT {column['default']}")
    return " ".join(fragments)


def _table_ddl(table, spec):
    _assert_identifier(table)
    lines = [_column_ddl(column) for column in spec["columns"]]
    primary_key = spec["primary_key"]
    lines.append(
        f"CONSTRAINT {_assert_identifier(primary_key['name'])} "
        f"PRIMARY KEY ({', '.join(primary_key['columns'])})"
    )
    for unique in spec["uniques"]:
        lines.append(
            f"CONSTRAINT {_assert_identifier(unique['name'])} "
            f"UNIQUE ({', '.join(unique['columns'])})"
        )
    for check in spec["checks"]:
        lines.append(
            f"CONSTRAINT {_assert_identifier(check['name'])} "
            f"CHECK ({check['expression']})"
        )
    for foreign_key in spec["foreign_keys"]:
        fragments = [
            f"CONSTRAINT {_assert_identifier(foreign_key['name'])}",
            f"FOREIGN KEY ({', '.join(foreign_key['columns'])})",
            f"REFERENCES {foreign_key['references_table']} "
            f"({', '.join(foreign_key['references_columns'])})",
        ]
        if foreign_key["on_delete"] != "NO ACTION":
            fragments.append(f"ON DELETE {foreign_key['on_delete']}")
        if foreign_key["on_update"] != "NO ACTION":
            fragments.append(f"ON UPDATE {foreign_key['on_update']}")
        lines.append(" ".join(fragments))
    body = ",\n ".join(lines)
    return f"CREATE TABLE {table} (\n {body}\n);"


def _index_ddl(index):
    _assert_identifier(index["name"])
    unique = "UNIQUE " if index["unique"] else ""
    columns = []
    for name, descending in zip(index["columns"], index["descending"]):
        columns.append(f"{name} DESC" if descending else name)
    statement = (
        f"CREATE {unique}INDEX {index['name']} ON {index['table']} "
        f"({', '.join(columns)})"
    )
    if index["predicate"]:
        statement += f" WHERE {index['predicate']}"
    return statement + ";"


def _trigger_ddl(trigger):
    _assert_identifier(trigger["name"])
    events = trigger["events"][0]
    if trigger["columns"]:
        events += f" OF {', '.join(trigger['columns'])}"
    return (
        f"CREATE TRIGGER {trigger['name']} BEFORE {events} ON {trigger['table']} "
        f"FOR EACH ROW EXECUTE FUNCTION {trigger['function']}();"
    )


