def provision_pg_schema(connection):
    """Provision the prod-1/v14 baseline into the connection's current schema.

    The caller owns the transaction.  An empty schema is created from scratch;
    a schema that already matches the contract exactly is an idempotent no-op;
    anything else fails closed with :class:`PostgresSchemaIncompatibleError`
    and is never dropped, altered or repaired.
    """
    _require_server_encoding(connection)
    relations = _schema_relation_names(connection)
    functions = _schema_function_names(connection)
    if relations or functions:
        try:
            status = validate_pg_schema(connection)
        except PostgresSchemaError as exc:
            raise PostgresSchemaIncompatibleError(
                "existing schema is not the SGAA prod-1/v14 PostgreSQL baseline; "
                "explicit provisioning refuses to drop, alter or repair it: "
                f"{exc}"
            ) from exc
        return {"status": "already_provisioned", **status}
    for statement in PG_SCHEMA_STATEMENTS:
        connection.execute(statement)
    status = validate_pg_schema(connection)
    return {"status": "provisioned", **status}


def _require_database_url():
    url = (os.environ.get("DATABASE_URL") or "").strip()
    if not url:
        raise PostgresProvisioningError(
            "DATABASE_URL is required for explicit PostgreSQL provisioning"
        )
    if not url.startswith(("postgres://", "postgresql://")):
        raise PostgresProvisioningError(
            "explicit PostgreSQL provisioning refuses non-PostgreSQL DATABASE_URL"
        )
    return url


def _safe_url_label(url):
    match = re.match(r"^([a-z]+://[^/@]*@)?([^/]+)/(.*)$", url)
    if not match:
        return "<configured>"
    return f"{match.group(2)}/{match.group(3)}"


def _connect_database(url, *, autocommit=False):
    import psycopg

    return psycopg.connect(url, prepare_threshold=None, autocommit=autocommit)


def validate_database(database_url):
    """Open ``database_url`` and run the read-only validator once."""
    connection = _connect_database(database_url)
    try:
        result = validate_pg_schema(connection)
        connection.rollback()
        return result
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()


def provision_database(database_url):
    """Provision ``database_url`` in a single transaction and commit."""
    connection = _connect_database(database_url)
    try:
        result = provision_pg_schema(connection)
        connection.commit()
        return result
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()


_USAGE = (
    "usage: python -m app.pg_schema <provision|validate>\n"
    "\n"
    "Explicit PostgreSQL schema operations for the SGAA prod-1/v14 baseline.\n"
    "DATABASE_URL must be a PostgreSQL URL. 'provision' creates the baseline\n"
    "from an empty schema or is a no-op when it already matches; it never\n"
    "drops, alters or repairs an existing schema.\n"
)


def main(argv=None):
    arguments = list(sys.argv[1:] if argv is None else argv)
    if not arguments or arguments[0] in {"-h", "--help"}:
        stream = sys.stderr if not arguments else sys.stdout
        print(_USAGE, file=stream)
        return 2 if not arguments else 0
    command = arguments[0]
    if command not in {"provision", "validate"}:
        print(_USAGE, file=sys.stderr)
        return 2
    try:
        url = _require_database_url()
        if command == "provision":
            result = provision_database(url)
            print(
                f"provision: {result['status']} "
                f"(epoch={result['schema_epoch']} version={result['schema_version']} "
                f"tables={result['table_count']} triggers={result['trigger_count']} "
                f"database={_safe_url_label(url)})"
            )
        else:
            result = validate_database(url)
            print(
                f"validate: ok "
                f"(epoch={result['schema_epoch']} version={result['schema_version']} "
                f"tables={result['table_count']} database={_safe_url_label(url)})"
            )
        return 0
    except PostgresSchemaError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # pragma: no cover - psycopg/environment failures
        print(f"error: {exc.__class__.__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
