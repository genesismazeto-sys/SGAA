    mapping = {}
    for table, spec in PG_TABLE_SPECS.items():
        primary_key = spec["primary_key"]
        mapping[primary_key["name"]] = {
            "kind": "primary_key",
            "table": table,
            "fields": list(primary_key["columns"]),
        }
        for unique in spec["uniques"]:
            mapping[unique["name"]] = {
                "kind": "unique",
                "table": table,
                "fields": list(unique["columns"]),
            }
        for check in spec["checks"]:
            mapping[check["name"]] = {
                "kind": "check",
                "table": table,
                "rule": check["expression"],
            }
        for foreign_key in spec["foreign_keys"]:
            mapping[foreign_key["name"]] = {
                "kind": "foreign_key",
                "table": table,
                "fields": list(foreign_key["columns"]),
                "references_table": foreign_key["references_table"],
                "references_fields": list(foreign_key["references_columns"]),
                "on_delete": foreign_key["on_delete"],
                "on_update": foreign_key["on_update"],
            }
    return mapping


