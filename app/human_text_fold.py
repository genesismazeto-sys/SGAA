def _single_pairs():
    for source, target, count, stride in _SINGLE_RUNS:
        for index in range(count):
            yield source + index * stride, target + index * stride


def _deletions():
    for first, last in _DELETION_RANGES:
        yield from range(first, last + 1)


def _build_translate_table():
    table = {code_point: None for code_point in _deletions()}
    for source, target in _single_pairs():
        table[source] = target
    for source, target in _EXPANSIONS:
        table[source] = target
    first, last = _HANGUL_SYLLABLES
    for code_point in range(first, last + 1):
        table[code_point] = _hangul_decomposition(code_point)
    return table


_TRANSLATE_TABLE = _build_translate_table()


def fold(value) -> str:
    """The human-text comparison key (see ``app.text.human_text_key``)."""
    text = str(value or "").translate(_TRANSLATE_TABLE)
    return " ".join(part for part in text.split(" ") if part)


