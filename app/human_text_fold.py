"""Frozen low-level authority for SGAA human-text folding.

``app.text.human_text_key`` is the public owner of the human-text comparison
key (names, titles, descriptions); this module is its single low-level
implementation.  Historically the key was computed as: Unicode compatibility
decomposition (NFKD), every combining mark (category M) dropped, full Unicode
case folding, whitespace runs collapsed to one space and the ends trimmed.

That pipeline is frozen here as its EFFECTIVE PER-CODE-POINT result under
Unicode ``UNICODE_VERSION`` -- nothing at run time consults a Unicode database
(neither the host Python's ``unicodedata`` nor PostgreSQL's ``normalize()``,
whose tables differ between PostgreSQL 15, 16 and 17).  Per code point the
result is one of:

* identity (omitted from the data);
* deletion (``_DELETION_RANGES``: combining marks and the few characters whose
  decomposition is only marks);
* one code point (``_SINGLE_RUNS``, run-length encoded);
* several code points (``_EXPANSIONS``);
* the Hangul syllable block (``_HANGUL_SYLLABLES``), decomposed by the fixed
  arithmetic of the Unicode standard instead of 11,172 literal entries.

Whitespace is mapped to U+0020 inside the mapping; the fold then collapses
space runs and trims.  The per-code-point form is exact because (verified by
``derive_mapping``) every character with a non-zero combining class is a mark,
so NFKD's canonical reordering never changes what survives, and every output
character maps to itself, so applying the mapping once per input code point --
in any order -- is the whole transformation.

``derive_mapping`` re-derives the data from a supplied ``unicodedata`` module
for verification only: it is never called at import or by :func:`fold`, and it
refuses any Unicode version other than ``UNICODE_VERSION``.  ``MAPPING_SHA256``
is part of the PostgreSQL schema contract, and ``pg_function_sql`` renders the
same data as the extension-free ``sgaa_human_text_key`` helper.
"""
