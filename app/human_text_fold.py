def _hangul_decomposition(code_point: int) -> str:
    index = code_point - _HANGUL_SYLLABLES[0]
    lead = chr(_HANGUL_L_BASE + index // _HANGUL_N_COUNT)
    vowel = chr(_HANGUL_V_BASE + (index % _HANGUL_N_COUNT) // _HANGUL_T_COUNT)
    trail = index % _HANGUL_T_COUNT
    return lead + vowel + (chr(_HANGUL_T_BASE + trail) if trail else "")


