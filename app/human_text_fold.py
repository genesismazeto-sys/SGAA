#: ``translate()`` tiers, as code-point range sets: a string made only of
#: characters inside a tier needs only that tier's mapping entries
#: (``translate`` scans its list per character, so ordinary Portuguese text --
#: Latin letters plus typographic punctuation -- never pays for the whole
#: table).  The first tier is ASCII; the last covers everything.
_PG_TIERS = (
    ((0x0001, 0x007F),),
    ((0x0001, 0x024F), (0x2000, 0x206F)),
    ((0x0001, _MAX_CODE_POINT),),
)


def _in_ranges(code_point, ranges):
    return any(first <= code_point <= last for first, last in ranges)


def pg_function_plan():
    """The data the PostgreSQL helper is rendered from (also used by tests).

    ``tiers``: ``(ranges, from, to)`` for ``translate`` -- single mappings,
    then deletions (characters of ``from`` beyond ``to`` are removed).
    ``expansions``: ``(source, target)`` applied per character afterwards,
    together with the Hangul rule, only when ``per_char_ranges`` matches.
    """
    singles = sorted(_single_pairs())
    deletions = sorted(_deletions())
    tiers = []
    for ranges in _PG_TIERS:
        tier_singles = [(s, t) for s, t in singles if _in_ranges(s, ranges)]
        tier_deletions = [d for d in deletions if _in_ranges(d, ranges)]
        tiers.append(
            (
                ranges,
                "".join(chr(s) for s, _ in tier_singles) + "".join(chr(d) for d in tier_deletions),
                "".join(chr(t) for _, t in tier_singles),
            )
        )
    expansions = [(chr(source), target) for source, target in _EXPANSIONS]
    per_char = sorted([ord(s) for s, _ in expansions] + list(range(_HANGUL_SYLLABLES[0], _HANGUL_SYLLABLES[1] + 1)))
    return {
        "tiers": tiers,
        "expansions": expansions,
        "per_char_ranges": _ranges(per_char),
        "hangul": _HANGUL_SYLLABLES,
    }


def _pg_escape(text: str) -> str:
    """Body of a PostgreSQL ``E''`` literal spelling every code point."""
    return "".join(
        f"\\u{ord(char):04X}" if ord(char) <= 0xFFFF else f"\\U{ord(char):08X}"
        for char in text
    )


def _pg_class(ranges) -> str:
    return "".join(
        _pg_escape(chr(first)) if first == last else f"{_pg_escape(chr(first))}-{_pg_escape(chr(last))}"
        for first, last in ranges
    )


def pg_function_sql(function_name: str) -> str:
    """``CREATE FUNCTION`` statement computing :func:`fold` on PostgreSQL.

    Uses no Unicode database of the server (no ``normalize()``): a tiered
    ``translate`` applies the single mappings and deletions; a per-character
    pass, run only when an expansion source or a Hangul syllable is present,
    applies the multi-code-point mappings (flat array lookup) and the Hangul
    arithmetic; space runs are then collapsed and trimmed.  ``NULL`` folds to
    ``''`` (deliberately not STRICT).
    """
    plan = pg_function_plan()
    (_, ascii_from, ascii_to), (latin_ranges, latin_from, latin_to), (_, full_from, full_to) = plan["tiers"]
    sources = ", ".join(f"E'{_pg_escape(s)}'" for s, _ in plan["expansions"])
    targets = ", ".join(f"E'{_pg_escape(t)}'" for _, t in plan["expansions"])
    first, last = plan["hangul"]
    hangul_index = f"(ascii(c.ch) - {first})"
    return f"""
CREATE FUNCTION {function_name}(value text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $fn$
  SELECT btrim(regexp_replace(p.t, ' {{2,}}', ' ', 'g'), ' ')
    FROM (SELECT coalesce(value, '') AS t) AS s,
         LATERAL (SELECT CASE
                    WHEN octet_length(s.t) = char_length(s.t)
                      THEN translate(s.t, E'{_pg_escape(ascii_from)}', E'{_pg_escape(ascii_to)}')
                    WHEN s.t !~ E'[^{_pg_class(latin_ranges)}]'
                      THEN translate(s.t, E'{_pg_escape(latin_from)}', E'{_pg_escape(latin_to)}')
                    ELSE translate(s.t, E'{_pg_escape(full_from)}', E'{_pg_escape(full_to)}')
                  END AS t) AS m,
         LATERAL (SELECT CASE
                    WHEN m.t !~ E'[{_pg_class(plan["per_char_ranges"])}]' THEN m.t
                    ELSE (SELECT coalesce(string_agg(
                            CASE
                              WHEN ascii(c.ch) BETWEEN {first} AND {last}
                                THEN chr({_HANGUL_L_BASE} + {hangul_index} / {_HANGUL_N_COUNT})
                                     || chr({_HANGUL_V_BASE} + ({hangul_index} % {_HANGUL_N_COUNT}) / {_HANGUL_T_COUNT})
                                     || CASE WHEN {hangul_index} % {_HANGUL_T_COUNT} > 0
                                             THEN chr({_HANGUL_T_BASE} + {hangul_index} % {_HANGUL_T_COUNT})
                                             ELSE '' END
                              ELSE coalesce(
                                (ARRAY[{targets}]::text[])[array_position(ARRAY[{sources}]::text[], c.ch)],
                                c.ch)
                            END, '' ORDER BY c.n), '')
                            FROM regexp_split_to_table(m.t, '') WITH ORDINALITY AS c(ch, n))
                  END AS t) AS p
$fn$
"""


