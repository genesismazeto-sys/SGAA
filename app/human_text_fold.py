def _mapping_document(unicode_version, deletion_ranges, single_runs, expansions, hangul):
    return {
        "unicode_version": unicode_version,
        "deletion_ranges": [list(item) for item in deletion_ranges],
        "single_runs": [list(item) for item in single_runs],
        "expansions": [list(item) for item in expansions],
        "hangul_syllables": list(hangul),
    }


def _digest(document) -> str:
    payload = json.dumps(document, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("ascii")).hexdigest()


def mapping_sha256() -> str:
    """Digest of the frozen mapping data shipped in this module."""
    return _digest(
        _mapping_document(
            UNICODE_VERSION, _DELETION_RANGES, _SINGLE_RUNS, _EXPANSIONS, _HANGUL_SYLLABLES
        )
    )


def _ranges(code_points):
    ranges = []
    for code_point in code_points:
        if ranges and ranges[-1][1] == code_point - 1:
            ranges[-1][1] = code_point
        else:
            ranges.append([code_point, code_point])
    return [tuple(item) for item in ranges]


def _runs(pairs):
    """Run-length encode sorted ``(source, target)`` pairs.

    A run ``(source, target, count, stride)`` maps ``source + i * stride`` to
    ``target + i * stride`` for ``i`` in ``range(count)``.
    """
    runs = []
    index = 0
    while index < len(pairs):
        source, target = pairs[index]
        stride = 1
        if index + 1 < len(pairs):
            next_source, next_target = pairs[index + 1]
            step = next_source - source
            if step in (1, 2) and next_target - target == step:
                stride = step
        count = 1
        while index + count < len(pairs) and pairs[index + count] == (
            source + count * stride,
            target + count * stride,
        ):
            count += 1
        runs.append((source, target, count, stride if count > 1 else 1))
        index += count
    return runs


def derive_mapping(unicodedata_module):
    """Re-derive the mapping document from ``unicodedata_module`` (verification).

    Refuses a Unicode database other than ``UNICODE_VERSION`` -- in the module
    or in the interpreter, whose ``str.casefold``/``str.isspace`` it uses -- and
    refuses data that breaks the per-code-point exactness properties.
    """
    import unicodedata as interpreter_unicodedata

    version = getattr(unicodedata_module, "unidata_version", None)
    if version != UNICODE_VERSION:
        raise ValueError(
            f"unicodedata {version!r} differs from the frozen human-text fold "
            f"version {UNICODE_VERSION!r}; re-derive and re-record deliberately"
        )
    if interpreter_unicodedata.unidata_version != UNICODE_VERSION:
        raise ValueError(
            f"interpreter Unicode database {interpreter_unicodedata.unidata_version!r} "
            f"differs from the frozen human-text fold version {UNICODE_VERSION!r}"
        )
    normalize = unicodedata_module.normalize
    category = unicodedata_module.category
    combining = getattr(unicodedata_module, "combining", None)

    def effective(char):
        decomposed = normalize("NFKD", char)
        kept = "".join(c for c in decomposed if not category(c).startswith("M"))
        return "".join(" " if c.isspace() else c for c in kept.casefold())

    deletions, pairs, expansions, outputs = [], [], [], set()
    first, last = _HANGUL_SYLLABLES
    for code_point in range(_MAX_CODE_POINT + 1):
        if code_point in _SURROGATES:
            continue
        char = chr(code_point)
        if combining is not None and combining(char) and not category(char).startswith("M"):
            raise ValueError(f"U+{code_point:04X} reorders under NFKD but is not a mark")
        result = effective(char)
        if first <= code_point <= last:
            if result != _hangul_decomposition(code_point):
                raise ValueError(f"U+{code_point:04X} breaks the Hangul decomposition rule")
            outputs.update(result)
            continue
        if result == char:
            continue
        outputs.update(result)
        if not result:
            deletions.append(code_point)
        elif len(result) == 1:
            pairs.append((code_point, ord(result)))
        else:
            expansions.append((code_point, result))
    not_final = sorted(ord(c) for c in outputs if effective(c) != c)
    if not_final:
        raise ValueError(f"mapping outputs are not fixed points: {not_final[:5]!r}")
    return _mapping_document(version, _ranges(deletions), _runs(pairs), expansions, _HANGUL_SYLLABLES)


def derive_mapping_sha256(unicodedata_module) -> str:
    """Digest of the mapping re-derived from ``unicodedata_module``."""
    return _digest(derive_mapping(unicodedata_module))


